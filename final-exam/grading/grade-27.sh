#!/usr/bin/env bash
source "$(dirname "$0")/lib.sh"
need curl
NS=ex280-t27
HOST=secure-app.apps-crc.testing
ns_exists "$NS" || fail "namespace $NS does not exist"

# --- Service must be annotated so the service CA issues the cert ---
oc get svc secure-app -n "$NS" >/dev/null 2>&1 || fail "Service secure-app not found"
ANN=$(oc get svc secure-app -n "$NS" -o jsonpath='{.metadata.annotations.service\.beta\.openshift\.io/serving-cert-secret-name}' 2>/dev/null)
[ "$ANN" = "secure-app-tls" ] \
  || fail "Service secure-app is missing annotation service.beta.openshift.io/serving-cert-secret-name=secure-app-tls (got: '$ANN')"

# --- the Secret must have been GENERATED by the service CA, not hand-made ---
oc get secret secure-app-tls -n "$NS" >/dev/null 2>&1 || fail "Secret secure-app-tls not found"
OWNER=$(oc get secret secure-app-tls -n "$NS" -o jsonpath='{.metadata.annotations.service\.beta\.openshift\.io/originating-service-name}' 2>/dev/null)
[ "$OWNER" = "secure-app" ] \
  || fail "Secret secure-app-tls was not generated by the service CA for Service secure-app (missing originating-service-name annotation) — do not create this Secret by hand"

# the issued cert's SAN is <service>.<ns>.svc
CRT=$(oc get secret secure-app-tls -n "$NS" -o jsonpath='{.data.tls\.crt}' | base64 -d 2>/dev/null)
echo "$CRT" | openssl x509 -noout -text 2>/dev/null | grep -q "secure-app.${NS}.svc" \
  || fail "the certificate in secure-app-tls has no SAN for secure-app.${NS}.svc"

# --- workload ready ---
oc get deployment secure-app -n "$NS" >/dev/null 2>&1 || fail "Deployment secure-app not found"
oc rollout status deployment/secure-app -n "$NS" --timeout=150s >/dev/null 2>&1 \
  || fail "Deployment secure-app never became ready"

# --- Route: reencrypt + destinationCACertificate ---
oc get route secure-app -n "$NS" >/dev/null 2>&1 || fail "Route secure-app not found"
TERM=$(oc get route secure-app -n "$NS" -o jsonpath='{.spec.tls.termination}')
[ "$TERM" = "reencrypt" ] || fail "Route termination is '$TERM', expected 'reencrypt'"

RHOST=$(oc get route secure-app -n "$NS" -o jsonpath='{.spec.host}')
[ "$RHOST" = "$HOST" ] || fail "Route host is '$RHOST', expected '$HOST'"

DCA=$(oc get route secure-app -n "$NS" -o jsonpath='{.spec.tls.destinationCACertificate}')
[ -n "$DCA" ] || fail "Route has no destinationCACertificate — the router cannot verify the pod's service-CA certificate without it"
echo "$DCA" | grep -q "BEGIN CERTIFICATE" || fail "destinationCACertificate does not look like a PEM certificate"

# --- end to end through the router ---
CODE=$(curl -s -o /dev/null -w '%{http_code}' --max-time 25 -k \
        --resolve "${HOST}:443:127.0.0.1" "https://${HOST}/" 2>/dev/null)
case "$CODE" in
  2*) ;;
  503) fail "router returned 503 for https://${HOST}/ — the re-encrypt connection to the pod failed (usually a wrong or missing destinationCACertificate)";;
  *)  fail "https://${HOST}/ returned HTTP $CODE, expected 2xx";;
esac

pass "service-CA issued secure-app-tls, pod terminates TLS on 8443, reencrypt route verified end to end (HTTP $CODE)"
